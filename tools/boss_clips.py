# Marshal Yan's clips. exec'd by build_boss.py (fills CLIPS, HITS, EVENTS, LOOPS). 60 fps, frame 1 = t0.
# Poses are in rigkit character space (left, forward, up) metres. The glaive is always described by
# the point midway between the hands (c), the direction the blade points (az = degrees from forward
# toward his left, el = degrees up; el beyond +-90 swings over the top / underneath) and the hand
# spacing s. The right fist sits `lead` of the spacing ahead of c. Blade tip = right fist + 1.56 m.
import math


def D(az, el):
    a, e = math.radians(az), math.radians(el)
    return (math.sin(a) * math.cos(e), math.cos(a) * math.cos(e), math.sin(e))


def GV(c, az, el, s=0.62, lead=0.5, edge=None):
    w = D(az, el)
    d = dict(gR=tuple(c[i] + w[i] * s * lead for i in range(3)), wR=w, tw=-s, two=1.0,
             gL=tuple(c[i] - w[i] * s * (1 - lead) for i in range(3)))
    if edge is not None:
        d['cR'] = edge
    return d


def mix(a, b_, t):
    return tuple(a[i] + (b_[i] - a[i]) * t for i in range(len(a)))


class Clip:
    def __init__(self, name, base, loop=False):
        self.name, self.k = name, {}
        self.at(1, base)
        if loop:
            LOOPS.append(name)

    def at(self, f, d=None, **kw):
        e = self.k.setdefault(int(round(f)), {})
        e.update(d or {})
        e.update(kw)
        return self

    def gv(self, f, c, az, el, s=0.62, lead=0.5, edge=None, **kw):
        return self.at(f, GV(c, az, el, s, lead, edge), **kw)

    def swing(self, f0, f1, c0, c1, az0, az1, el0, el1, s0=0.62, s1=None, lead=0.5, n=None, ease=sm, mid=None):
        """Blade travels from (az0, el0) to (az1, el1) between frames f0 and f1; the cutting edge leads.
        mid = (t, c) bends the hand path through a point."""
        s1 = s0 if s1 is None else s1
        n = n or max(2, int(round((f1 - f0) / 1.5)))
        for i in range(n + 1):
            t = i / n
            e = ease(t)
            az, el = az0 + (az1 - az0) * e, el0 + (el1 - el0) * e
            if mid:
                c = mix(c0, mid[1], e / mid[0]) if e < mid[0] else mix(mid[1], c1, (e - mid[0]) / (1 - mid[0]))
            else:
                c = mix(c0, c1, e)
            da, de = (az1 - az0), (el1 - el0)
            w0, w1 = D(az - da * 0.01, el - de * 0.01), D(az + da * 0.01, el + de * 0.01)
            edge = tuple(w1[j] - w0[j] for j in range(3))
            self.gv(f0 + (f1 - f0) * t, c, az, el, s0 + (s1 - s0) * e, lead, edge)
        return self

    def done(self, hits=(), **events):
        CLIPS[self.name] = sorted(self.k.items())
        HITS[self.name] = list(hits)
        if events:
            EVENTS[self.name] = events


